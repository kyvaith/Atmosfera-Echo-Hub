def caption_width(text: str) -> int:
    """Measure advances and final ink extents; unknown glyphs are bounded."""
    pen = right = 0
    for char in text:
        advance, ink = _GLYPHS.get(ord(char), (19, 19))
        right = max(right, pen + ink)
        pen += advance
    return max(right, pen)


def fit_caption(text: str, width: int) -> str:
    """Keep one bounded line and reserve room for its ellipsis."""
    if len(text) <= 40 and caption_width(text) <= width:
        return text
    prefix = text[:37]
    while prefix and caption_width(prefix + "...") > width:
        prefix = prefix[:-1]
    return prefix + "..."


def fit_wide_caption(text: str) -> str:
    return fit_caption(text, 288)


def fit_compact_caption(text: str) -> str:
    """Fit the existing 136px Roboto16 subtitles of compact Home tiles."""
    return fit_caption(text, 136)
